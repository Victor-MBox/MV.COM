/** Ключ живой сцены — компонент в components/caseInside/scenes */
export type InsideSceneKey = 'problem' | 'filters' | 'match' | 'seo' | 'party' | 'live' | 'steam' | 'mobile'

export type InsideChapter = {
	key: InsideSceneKey
	/** Слово метки без слэшей и номера: «задача» → // 01 · задача */
	label: string
	title: string
	/** Абзацы: что сделано и зачем */
	text: string[]
	/** «Как устроено» — короткие технические факты */
	how: string[]
	/** «Почему так» — одно решение и его причина */
	why: string
	/** Адрес в строке окна продукта */
	path: string
	/** Подпись сцены для диктора */
	scene: string
}

export type ArchNode = {
	key: string
	/** Номер-метка моно: 01 */
	title: string
	/** Что делает узел */
	what: string
	/** Почему он здесь */
	why: string
	/** Положение на ленте: main — путь запроса; up / down — ветки над и под ним */
	lane: 'main' | 'up' | 'down'
	/** Колонка ленты (0…), по которой узел стоит над/под узлом пути */
	col: number
}

