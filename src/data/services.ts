export function getServicesByGroup(group: string) {
	return SERVICES.filter(s => s.group === group)
}

export function getGroup(key: string | undefined) {
	return SERVICE_GROUPS.find(g => g.key === key)
}

export function getService(group: string | undefined, key: string | undefined) {
	return SERVICES.find(s => s.group === group && s.key === key)
}

export function getGroupStack(group: string) {
	return Array.from(new Set(getServicesByGroup(group).flatMap(s => s.stack)))
}

