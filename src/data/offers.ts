/**
 * Двенадцать офферов на языке задачи клиента (content.md §4.2): шесть основных (главная и первая группа /services),
 * пять новых от 22.10.2026 (мобильные приложения, интерактив, SEO, реклама, аналитика — ТЗ «расширить услуги») и
 * агентства строкой под сеткой. Страницы — /services/:offer и /services/promotion/:offer (parent). Порядок массива =
 * номер «услуга 0N» (offerNumber) — один и тот же на карточке и в шапке страницы; на /services карточки сгруппированы
 * (CATALOG_GROUPS), поэтому номера в группах идут не подряд. Старые 32 услуги из SERVICES не удаляются: они перечислены
 * в `services[]` как «что ещё делаю в этом направлении» внутри аккордеона на странице оффера.
 */
/** Формат работы в блоке стоимости: подпись, стартовая цена (у индивидуальной оценки её нет) и условия базового объёма */
export type OfferFormat = { label: string; price?: string; text: string }

/**
 * Дополнительный раздел страницы услуги (ТЗ от 22.10.2026): «Что входит в ведение» у рекламы, «Видимость в ответах
 * нейросетей» у SEO, пример у интерактива. Либо список `items`, либо абзац `text`; `note` — подпись моно под ним
 */
export type OfferExtra = {
	id: string
	label: string
	title: Headline
	lead?: string
	items?: string[]
	text?: string
	note?: string
	/** После какого раздела страницы стоит: после состава или после стоимости */
	after: 'outcomes' | 'price'
}

/** Раздел, внутри которого живёт страница услуги: /services/promotion/:key вместо /services/:key */
export type OfferParent = 'promotion'

export type Offer = {
	key: string
	/** Вложенный раздел: у SEO, рекламы и аналитики путь /services/promotion/:key (offerPath) */
	parent?: OfferParent
	/** Короткое название: карточка каталога, крошка и тема заявки */
	title: string
	/** H1 страницы услуги (ТЗ по текстам и SEO от 21.10.2026); title и description страницы — OFFER_META в meta.ts */
	heading: string
	/** Описание на карточке каталога (главная и /services) и, если нет `lead`, лид шапки страницы услуги */
	line: string
	/** Лид шапки страницы услуги, когда он отличается от описания карточки (новые услуги от 22.10.2026) */
	lead?: string
	/** Для кого — три слова; с 21.10.2026 на карточках не выводится (карточка — название, описание, цена и срок) */
	forWhom: string
	priceFrom: string
	/** Уточнение цены в шапке страницы (моно рядом с бейджами): условия базового объёма, которые нельзя прятать */
	priceDetail?: string
	/**
	 * Цены частей оффера: на карточке каталога — строки «подпись — цена», в шапке страницы услуги — бейджи вместо одной
	 * «стоимость». Первая равна priceFrom (тест)
	 */
	prices?: { label: string; price: string }[]
	/** Цена одной строкой на карточке каталога вместо строк `prices` (SEO: только ежемесячный тариф, без аудита) */
	cardPrice?: string
	/** Условие после цены на карточке вместо срока: «одна платформа, готовые дизайн и API» */
	cardNote?: string
	/** Строка под ценами карточки: «Рекламный бюджет оплачивается отдельно» */
	cardFoot?: string
	term: string
	/** Подпись бейджа срока, если это не срок: у SEO «план работ и отчёт — каждый месяц» */
	termLabel?: string
	/** Срок не выводится на карточке каталога (доработка: срок зависит от задачи); на странице услуги он остаётся */
	hideTermOnCard?: boolean
	/** Подпись главной кнопки: «Обсудить лендинг» или общее «Обсудить задачу» */
	cta: string
	/** Свои четыре шага вместо общего процесса новой разработки (PROCESS): интеграции, доработка, агентства, новые услуги */
	process?: ProcessStep[]
	/** Кому подходит — три-пять ситуаций одной строкой */
	audience: string[]
	/** Кому не подходит — до двух ситуаций; пусто — колонка «не подходит» не выводится */
	notFor: string[]
	/**
	 * «Состав проекта» — возможности и работы по услуге на языке результата, а не обязательный комплект за стартовую
	 * цену. Термины для разработчика — в tech
	 */
	outcomes: string[]
	/** Пояснение под заголовком состава (доработка: чем направления работ отличаются от пакетов обслуживания) */
	outcomesLead?: string
	/** Подпись под списком состава: границы стартового объёма, что событие не равно продаже и т. п. */
	outcomesNote?: string
	/**
	 * Форматы работы в блоке стоимости (аудит / продвижение, настройка / ведение): подпись, цена и условия базового
	 * объёма. Если заданы, заменяют строку «стартовая стоимость»; цены — те же, что в бейджах шапки
	 */
	formats?: OfferFormat[]
	/** Абзац после форматов: что согласуем отдельно, что не оплачивается дважды */
	formatsNote?: string
	/** Что согласуем для оценки — строка над факторами цены; не фиксированный состав стартового предложения */
	estimate?: string
	/** Три фактора, от которых зависит цена */
	priceFactors: string[]
	/** Не входит в стоимость: материалы заказчика, сторонние расходы, работы сверх согласованного */
	notIncluded: string[]
	/** Формат оплаты, если не общий PAYMENT страницы услуги (разовая оплата, ежемесячно по плану) */
	payment?: string
	/** Заголовки секций, если общие не подходят: «Когда это нужно», «Состав работ», «Форматы работы», свой процесс */
	headings?: { fit?: Headline; outcomes?: Headline; price?: Headline; process?: Headline }
	/** Дополнительные разделы страницы после состава или стоимости */
	extras?: OfferExtra[]
	/** После запуска; если не задано — общий текст AFTER_LAUNCH из pricing.ts */
	afterLaunch?: string
	faq: Faq[]
	/** Строка финального обращения на странице услуги (с кнопкой `cta`); нет — блока нет, обращение даёт футер */
	ctaLead?: string
	/** Соседние услуги под обращением: ключи офферов или 'promotion' — обзор продвижения (relatedLinks) */
	related?: string[]
	/** Ключи из SERVICES — подуслуги направления; у услуг без аккордеона «Стек и детали» может быть пусто */
	services: string[]
	/** Категории кейсов для блока «Примеры»; нет совпадений или пусто — блок не показывается */
	categories: string[]
	/** Единственное место на странице с названиями технологий; нет — аккордеона «Стек и детали» на странице нет */
	tech?: {
		stack: string[]
		notes: string[]
	}
}

