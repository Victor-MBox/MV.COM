/** Ссылки «смежные услуги» на странице услуги: ключи офферов и 'promotion' — обзор способов продвижения */
export function relatedLinks(o: Pick<Offer, 'related'>): { label: string; to: string }[] {
	return (o.related ?? []).flatMap(key => {
		if (key === 'promotion') return [{ label: 'Все способы продвижения', to: PROMOTION_PATH }]
		const offer = getOffer(key)
		return offer ? [{ label: offer.title, to: offerPath(offer) }] : []
	})
}
