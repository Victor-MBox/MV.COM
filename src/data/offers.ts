/**
 * Семь офферов на языке задачи клиента (content.md §4.2). Это каталог главной и /services (шесть карточек, агентства —
 * отдельной строкой под сеткой) и страницы /services/:offer. Порядок массива = порядок карточек и номер «услуга 0N».
 * Старые 32 услуги из SERVICES не удаляются: они перечислены в `services[]` как
 * «что ещё делаю в этом направлении» внутри аккордеона на странице оффера.
 */
export type Offer = {
	key: string
	/** Короткое название: карточка каталога, крошка и тема заявки */
	title: string
	/** H1 страницы услуги (ТЗ по текстам и SEO от 21.10.2026); title и description страницы — OFFER_META в meta.ts */
	heading: string
	/** Описание на карточке каталога (главная и /services) и лид шапки страницы услуги */
	line: string
	/** Для кого — три слова; с 21.10.2026 на карточках не выводится (карточка — название, описание, цена и срок) */
	forWhom: string
	priceFrom: string
	/** Уточнение цены, когда одной цифры мало */
	priceDetail?: string
	/**
	 * Цены частей оффера: на карточке каталога — строки «подпись — цена», в шапке страницы услуги — бейджи вместо одной
	 * «стоимость». Первая равна priceFrom (тест)
	 */
	prices?: { label: string; price: string }[]
	term: string
	/** Срок не выводится на карточке каталога (доработка: срок зависит от задачи); на странице услуги он остаётся */
	hideTermOnCard?: boolean
	/** Подпись главной кнопки: «Обсудить лендинг» или общее «Обсудить задачу» */
	cta: string
	/** Свои четыре шага вместо общего процесса новой разработки (PROCESS): интеграции, доработка, агентства */
	process?: ProcessStep[]
	/** Кому подходит — три ситуации одной строкой */
	audience: string[]
	/** Кому не подходит — одна-две ситуации. Честное «не ко мне» отсеивает нецелевые заявки */
	notFor: string[]
	/**
	 * «Состав проекта» — возможности и работы по услуге на языке результата, а не обязательный комплект за стартовую
	 * цену. Термины для разработчика — в tech
	 */
	outcomes: string[]
	/** Пояснение под заголовком состава (доработка: чем направления работ отличаются от пакетов обслуживания) */
	outcomesLead?: string
	/** Что согласуем для оценки — строка над факторами цены; не фиксированный состав стартового предложения */
	estimate?: string
	/** Три фактора, от которых зависит цена */
	priceFactors: string[]
	/** Не входит в стоимость: материалы заказчика, сторонние расходы, работы сверх согласованного */
	notIncluded: string[]
	/** Заголовки секций, если общие не подходят: «Состав работ» у доработки, свой процесс у интеграций и доработки */
	headings?: { outcomes?: Headline; process?: Headline }
	/** После запуска; если не задано — общий текст AFTER_LAUNCH из pricing.ts */
	afterLaunch?: string
	faq: Faq[]
	/** Ключи из SERVICES — подуслуги направления */
	services: string[]
	/** Категории кейсов для блока «Примеры»; нет совпадений — блок не показывается */
	categories: string[]
	/** Единственное место на странице с названиями технологий */
	tech: {
		stack: string[]
		notes: string[]
	}
}

