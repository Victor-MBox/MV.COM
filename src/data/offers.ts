export function getOffer(key: string | undefined) {
	return OFFERS.find(o => o.key === key)
}

/** Обзор способов продвижения — родительская страница SEO, рекламы и аналитики (PromotionPage, data/promotion.ts) */
export const PROMOTION_PATH = '/services/promotion'

/** Путь страницы услуги: /services/:key, у услуг раздела продвижения — /services/promotion/:key */
export const offerPath = (o: Pick<Offer, 'key' | 'parent'>) => (o.parent ? `/services/${o.parent}/${o.key}` : `/services/${o.key}`)

/** Номер услуги «01»…«12» — по месту в OFFERS: один и тот же на карточке каталога и в метке шапки страницы */
export const offerNumber = (o: Pick<Offer, 'key'>) => String(OFFERS.findIndex(x => x.key === o.key) + 1).padStart(2, '0')

