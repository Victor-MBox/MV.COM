/**
 * Семь офферов на языке задачи клиента (content.md §4.2). Это витрина /services и /services/:offer.
 * Старые 32 услуги из SERVICES не удаляются: они перечислены в `services[]` как
 * «что ещё делаю в этом направлении» внутри аккордеона на странице оффера.
 */
export type Offer = {
	key: string
	title: string
	/** Одна строка на карточке и в шапке страницы */
	line: string
	/** Для кого — три слова на карточке /services */
	forWhom: string
	priceFrom: string
	/** Уточнение цены, когда одной цифры мало */
	priceDetail?: string
	/** Цены частей оффера разного масштаба: карточки каталога и витрина выводят их строками вместо одной priceFrom */
	prices?: { label: string; price: string }[]
	term: string
	/** Подпись главной кнопки в винительном падеже: «Обсудить лендинг» */
	cta: string
	/** Кому подходит — три ситуации одной строкой */
	audience: string[]
	/** Кому не подходит — одна-две ситуации. Честное «не ко мне» отсеивает нецелевые заявки */
	notFor: string[]
	/** Что получите — результаты, а не работы */
	outcomes: string[]
	/** Три фактора, от которых зависит цена */
	priceFactors: string[]
	notIncluded: string[]
	/** После запуска; если не задано — общий текст AFTER_LAUNCH из pricing.ts */
	afterLaunch?: string
	faq: Faq[]
	/** Ключи из SERVICES — подуслуги направления */
	services: string[]
	/** Категории кейсов для блока «Примеры»; нет совпадений — блок не показывается */
	categories: string[]
	/** Единственное место на странице с названиями технологий */
	tech: {
		stack: string[]
		notes: string[]
	}
}

