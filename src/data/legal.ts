export const LEGAL_LINKS: LegalDoc[] = [PRIVACY, CONSENT, COOKIES]

/** Подпись кнопки футера, открывающей окно настроек (ТЗ §3, §10) */
export const COOKIE_SETTINGS_LABEL = 'Настройки cookie'

export function getLegalDoc(pathname: string) {
	const path = pathname.replace(/\/+$/, '') || '/'
	return LEGAL_LINKS.find(d => d.path === path)
}

/**
 * Канонический текст документа для контрольной суммы (server/legal.json, тест legal.test.ts): заголовок и все строки
 * блоков через перевод строки. Разметка ссылок остаётся как есть — это тоже часть текста
 */
export function legalDocumentText(doc: LegalDoc) {
	const lines: string[] = [doc.title, `v${doc.version} ${doc.effectiveDate}`]
	for (const b of doc.blocks) {
		if (b.type === 'ul') lines.push(...b.items)
		else if (b.type === 'table') lines.push(b.head.join(' | '), ...b.rows.map(r => r.join(' | ')))
		else lines.push(b.text)
	}
	return lines.join('\n')
}

/** Все строки документа (для тестов на заглушки и факты) */
export function legalDocumentStrings(doc: LegalDoc) {
	return legalDocumentText(doc).split('\n')
}

